// content/checkIntent.js 的「過寬關鍵字」回歸測試 —— 系統性收集真實案例，取代單靠玩家玩到才發現。
//
// 起因：玩家對 NPC 說「這到底是什麼怪物啊……大佬，再來該怎麼做啊？」純粹在問下一步，
// 卻因為句子裡出現「怪物」二字，被 INTENT_TABLE 的秘識(Occult Lore)關鍵字誤判成检定意圖
// （見 content/checkIntent.js 2026-09-02 的修正註解）。
//
// [誠實的免責聲明，2026-09-03] 這支測試原本想寫成「自動把每個關鍵字塞進一句模板問句，
// 檢查會不會被誤判」的全自動掃描器，寫完才發現那是空話：INTENT_TABLE 的比對是單純的
// `text.includes(keyword)`，只要把關鍵字逐字塞進任何句子，它一定會命中自己
// （試過就知道：把「砍」塞進「這到底是什麼砍啊」，一樣會被判成格鬥檢定——但那句話
// 本身在中文裡就不通順，沒有玩家會這樣打字）。「怪物」之所以是真的 bug，是因為它是
// 一個**名詞**、自然地放得進「這到底是什麼X啊」這種提問句；「砍」是動詞，塞不進去，
// 所以現實裡不會有人寫出那種句子去踩到它。
//
// 中文沒有詞性標記，這支專案也沒有接 NLP 函式庫，程式沒辦法自動判斷「這個詞放進
// 一句話裡文法通不通、玩家會不會真的這樣打字」——這件事目前只能靠人判斷。
// 所以這支測試改成**誠實的做法**：收集真實／寫實的玩家可能輸入的句子（含這次
// 與之後陸續發現的案例），把它們釘成回歸測試，而不是假裝有一個能自動證明「窮舉
// 所有關鍵字都安全」的腳本。發現新的誤判案例，照這個檔案的格式加一條測試就好。
import test from "node:test";
import assert from "node:assert/strict";
import { inferCheckParams } from "../content/checkIntent.js";

/**
 * 純對話／提問句語料庫：這些句子的共同點是「玩家在問話，不是在嘗試做那個技能
 * 對應的事」，而且已經確認目前的規則表**正確**回傳 requiresCheck:false。
 */
const CONFIRMED_FIXED = [
  {
    text: "「這到底是什麼怪物啊......」感到不寒而慄，轉頭看向陸遠，「那個，大佬，再來該怎麼做啊？」",
    reason: "純問路對話，「怪物」是驚呼用詞，不是要施展秘識分析（2026-09-02 修復）",
  },
  { text: "那個東西到底是什麼怪物？陸遠你見過嗎？", reason: "同上，換句話問法" },
];

test("純對話／提問句不會被誤判成需要擲骰（已修復的過寬關鍵字回歸語料庫）", () => {
  const failures = [];
  for (const { text, reason } of CONFIRMED_FIXED) {
    const params = inferCheckParams(text);
    if (params.requiresCheck) failures.push({ text, reason, got: params });
  }
  assert.deepEqual(
    failures,
    [],
    `以下純對話句被誤判成需要擲骰：\n${JSON.stringify(failures, null, 2)}`
  );
});

/**
 * [2026-09-03 新發現，已知、尚未修復的真實 bug]
 *
 * 用同樣的方法（在 INTENT_TABLE 裡找「本身既是名詞化話題、也是動詞」的關鍵字）
 * 另外手動驗證出 4 個新案例，全部是「交涉」技能的關鍵字。原因跟「怪物」類似但
 * 不完全一樣：玩家單純**轉述或詢問「別人」在做這件事**（不是自己要做），
 * 一樣會被誤判成玩家自己在執行交涉檢定。
 *
 * 這 4 個詞**不能**像「怪物」一樣直接從關鍵字表刪掉——它們是交涉檢定唯一的
 * 觸發詞，刪掉會讓真正的交涉意圖（「我威脅他交出武器」）偵測不到。要修對，
 * 需要能分辨「玩家自己在做」跟「玩家在轉述/詢問別人在做」，這需要額外設計
 * （不是簡單的刪詞），所以先誠實記錄現況，不倉促加一個沒充分驗證的啟發式規則。
 *
 * 這條測試斷言的是**現況**（目前仍會誤判），不是期望行為，所以斷言 requiresCheck
 * 為 true。修好之後：把斷言改成 false，並把這幾句話搬進上面的 CONFIRMED_FIXED，
 * 讓這條測試的存在本身變成「這件事還沒修」的提醒。
 */
const KNOWN_UNFIXED = [
  {
    text: "他一直用威脅的語氣說話，我們該怎麼辦？",
    reason: "轉述 NPC 的語氣，玩家自己沒有要威脅任何人",
  },
  {
    text: "你覺得他們會不會出言恐嚇我們？",
    reason: "詢問對方會不會恐嚇，不是玩家自己要恐嚇",
  },
  { text: "陸遠是不是在跟他們談判？", reason: "詢問陸遠的行為，不是玩家自己在談判" },
  {
    text: "我在想要不要試著說服他，但我還沒開口。",
    reason: "明確表示「還沒開口」，是猶豫/內心話，不是正在執行的行動",
  },
];

test("[已知問題，未修復] 威脅/恐嚇/談判/說服：轉述句目前仍會誤判成交涉檢定", () => {
  for (const { text, reason } of KNOWN_UNFIXED) {
    const params = inferCheckParams(text);
    assert.equal(
      params.requiresCheck,
      true,
      `「${text}」（${reason}）已經不會誤判了——把它搬進 CONFIRMED_FIXED，並刪掉這條測試裡對應的項目`
    );
  }
});
