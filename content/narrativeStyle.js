// [設計] 文筆風格層 —— 跟「規則契約層」刻意分開的兩層系統提示。
//
// 為什麼要分兩層(這是這個檔案存在的全部理由)：
//
//   規則契約層(promptContract.js 的 SYSTEM_INSTRUCTION)是**不可協商**的：
//   AI不能重算數字、不能因為玩家話術改變結果基調。這是專案最高原則第1、2條。
//
//   文筆層(這個檔案)是**可以隨時換掉**的：要寫得冷硬還是華麗、句子長還是短、
//   要不要寫角色內心戲——這些純粹是品味，換掉不影響遊戲的正確性。
//
// 如果把這兩件事混在同一段提示詞裡，遲早會出事：你為了調整文筆去改那段文字，
// 一不小心就把「不能自己編數字」那條規則的語氣改弱了，而且**你不會馬上發現**——
// 因為AI大部分時候還是會乖乖照做，只有在玩家開始用話術凹的時候才會破功。
// 分成兩層之後，改文筆永遠碰不到規則，這是結構上的保證，不是靠人記得小心。
//
// 組裝順序也是刻意的(見 composeSystemInstruction)：文筆要求放前面，規則契約放後面，
// 最後再補一句明確的優先序宣告。這樣就算某天你(或某個AI)寫了一段跟規則衝突的文筆提示詞，
// 模型讀到的最後一段話仍然是「規則優先於文筆」。

