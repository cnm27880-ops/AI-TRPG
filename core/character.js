// [設計] 戰鬥用角色檔案的資料形狀 —— 把角色的防御/護甲相關欄位整理成
// resolveCombatAction() 可以直接吃的形狀。
//
// [決策記錄 2026-08-15] 隨著 core/combat/defense.js 與 core/combat/armor.js 的
// 單一DC+單一護甲值簡化，這個形狀跟著大幅簡化：不再需要四層防御的個別欄位
// （格擋/盔甲/天生防御分開列），也不再需要傷害類型相關的欄位（免疫清單/各能量子類抗力/
// 物理DR/吸收），全部合併成三個數字。舊版的完整欄位保留在 git 歷史紀錄中。
//
// 大多數欄位目前仍是裝備/血統/改造提供的數值，這個引擎還沒有真正的裝備/血統資料
// (Phase 3才會有)，所以全部給預設值0，讓引擎在「空手空防具」的情況下也能正確跑完整套
// 流程，之後接上真實資源資料時，只要把這些欄位的數字填對就好，不用改動任何
// core/combat/ 的邏輯。

export function emptyCombatProfile() {
  return {
    skillCorrection: 0, // 技能補正，呼叫端算好傳進來(通常是 max(格鬥,體魄) 技能等級)
    equipmentDefense: 0, // 裝備/天生防御來源的加總(血統/改造/防具等)
    armor: 0, // 護甲值，傷害吸收用(見 core/combat/armor.js)
  };
}
