// [設計] 敘事結果分級契約 —— 規則書本身只定義「成功/失敗與margin」，沒有定義敘事該多誇張，
// 這個模組是我們自己補上的，目的是直接回應使用者的需求：
// 「AI除了看玩家的行動，也要看骰子做判斷，要是玩家說他很厲害，結果骰子失敗超徹底，那就尷尬了」
//
// 用法：每次 performCheck() 跑完，把結果丟進 classifyOutcome()，拿到一個「分級」跟「敘事指令」。
// 這個「敘事指令」是要放進餵給 AI 的 prompt 裡的一段話，用來鎖住 AI 的敘事基調，
// AI 不能因為玩家寫了「我超強」就无視這個分級亂寫劇情。
//
// 分級門檻目前是這個專案自己訂的草案，數字本身沒有規則書依據，之後可以依實際測玩調整，
// 但調整時一樣要更新 test/narration.test.js 鎖住新版行為，不能無測試地隨便改。
//
// ---------------------------------------------------------------------------
// [2026-08-16 改寫] 指令從「語氣描述」改成「必須兌現的結果」。
//
// 起因是實際測玩回報（逐字）：「骰子成功和失敗造成的影響沒有什麼決定性差異，
// 我成功了也會引來異形探查，失敗了AI就描述我可以再潛行一次，而沒有更強烈的戲劇張力」。
//
// 對照舊版指令就看得出原因：「行動確實成功，正常描寫達成目標的過程」——這句話沒有
// 要求任何**世界狀態的改變**，AI照著寫也可以寫出「你成功躲進陰影，但異形仍在搜索」，
// 完全合乎指令，玩家卻感覺不到自己成功了。失敗那一側更糟：「描寫合理的受挫」
// 直接被讀成「讓玩家再試一次」，於是同一個障礙可以卡三回合。
//
// 現在每一級都明講三件事：這一級**得到什麼**、**失去什麼**、以及**不准出現什麼收尾**。
// 「不准」那一條是最重要的——正面要求AI很容易照做一半，禁令才擋得住它回到原點。
// 真正讓成敗產生持續性差異的是 content/scenario/threat.js 的迫近度軌（那是引擎狀態，
// 會被寫進存檔），這裡的指令只負責「這一回合當下讀起來要有差別」。兩者缺一不可。
// ---------------------------------------------------------------------------

/** 每一級指令共用的結尾禁令，避免同一句話在六個分級裡各寫一次、日後改到不一致。 */
const NO_RESET_CLAUSE =
  "禁止把這一回合寫成「玩家可以再試一次同一件事」——同一個障礙、同一個方法不可以重來，" +
  "下一回合的處境必須跟這一回合開頭不同。";

/**
 * 失敗專用的禁令（2026-08-18 新增，見 Phase 5.3 任務3）。
 *
 * 為什麼失敗要有一條比 NO_RESET_CLAUSE 更硬的禁令：實測回報「失敗了AI就描述我可以
 * 再潛行一次」，而 NO_RESET_CLAUSE 那句「處境必須不同」對模型來說太好交差了——
 * 它只要把燈光改成閃爍的、把玩家從門左邊挪到門右邊，形式上就「不同」了，
 * 玩家實際上還是站在同一道門前面用同一個方法再試一次。
 *
 * 所以這裡把它寫成**空間上的禁令**：不准待在原地。位置、可用的方法、或誰在場，
 * 三者至少要有一樣被強制換掉。這是可以檢查的，「處境不同」不是。
 */
const FAIL_FORWARD_CLAUSE =
  "【嚴禁原地重試】嚴禁讓玩家待在原地用同樣的方法再試一次。" +
  "這一回合結束時，下列三件事至少要有一件被強制改變：玩家所在的位置、" +
  "剛才那個方法還能不能用、或是現場多了／少了誰。" +
  "把失敗寫成下面兩種形狀之一，不要寫成第三種：" +
  "(甲) 動作其實完成了，但引發了更糟的後果——門開了卻同時觸發警報、" +
  "撬開了櫃子卻弄斷手上的工具、藏好了卻把追兵引到隔壁房間、拿到了東西卻受了傷；" +
  "(乙) 動作徹底失敗，而且處境變得更危險——退路被封、被看見、掉到更低的地方、" +
  "手上的東西掉進拿不回來的地方。" +
  "禁止的第三種是「你失敗了，你重新調整呼吸準備再試一次」——那不是失敗，那是暫停。";

